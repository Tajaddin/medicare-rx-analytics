"""Write docs/DATA-DICTIONARY.md from the exported marts (types) and dbt's schema.yml (descriptions, grain).

python scripts/data_dictionary.py      (after `rx export`)
"""

from __future__ import annotations

from pathlib import Path

import pyarrow.parquet as pq
import yaml

ROOT = Path(__file__).resolve().parents[1]
MARTS = [
    "mart_drug_spend_trend",
    "mart_specialty_class_year",
    "mart_generic_opportunity",
    "mart_opioid_by_city",
    "mart_glp1_growth",
    "dim_drug",
]
# Columns whose meaning is not obvious from the name. Costs are gross Part D drug cost (before rebates).
NOTES = {
    "drug_class": "class from the reviewed rules in seeds/drug_classes.csv (ADR 0004); `other` = untracked",
    "claims": "Part D claims (prescriptions and refills)",
    "fills_30day": "claims standardised to 30-day supplies",
    "drug_cost": "gross Part D drug cost, US$, before manufacturer rebates",
    "prescribers": "distinct prescribers (NPI)",
    "cost_per_claim": "drug_cost / claims",
    "national_cost_per_claim": "same generic name, all states, from Part D Spending by Drug",
    "cost_growth_yoy": "drug_cost against the same generic name and class a year earlier; empty in the first year",
    "cost_rank_in_year": "rank by drug_cost within the year (1 = largest)",
    "share_of_specialty_claims": "the class's share of all claims by that specialty that year",
    "brand_fills": "30-day fills of branded products with this generic name",
    "generic_fills": "30-day fills dispensed as the generic",
    "savings_upper_bound": "brand_cost minus brand_fills x the generic's cost per fill, floored at 0; an upper bound",
    "brand_share_of_fills": "brand_fills / (brand_fills + generic_fills)",
    "all_claims": "every Part D claim by the city's prescribers",
    "opioid_claims": "claims in class opioid_analgesic (CDC definition; cough products excluded)",
    "opioid_day_supply": "days' supply of those claims",
    "oud_treatment_claims": "buprenorphine claims for opioid use disorder (naltrexone excluded, see ADR 0004)",
    "opioid_prescribers": "prescribers with at least one opioid analgesic row",
    "opioid_share_of_claims": "opioid_claims / all_claims",
    "oud_treatment_per_opioid_claim": "oud_treatment_claims / opioid_claims",
    "avg_opioid_days_per_claim": "opioid_day_supply / opioid_claims",
    "is_brand": "true when CMS's brand name differs from the generic name",
    "fl_claims_all_years": "Florida claims, all loaded years",
    "fl_cost_all_years": "Florida drug cost, all loaded years",
    "national_manufacturers_2024": "manufacturers of the product nationally, 2024",
    "national_spend_per_unit_2024": "average spending per dosage unit nationally, 2024 (weighted)",
    "national_spend_per_claim_2024": "average spending per claim nationally, 2024",
    "national_price_outlier_2024": "CMS flags the unit price as an outlier for 2024",
}


def main() -> None:
    schema = yaml.safe_load((ROOT / "dbt/models/schema.yml").read_text(encoding="utf-8"))
    models = {m["name"]: m for m in schema["models"]}
    lines = [
        "# Data dictionary",
        "",
        "Generated by `scripts/data_dictionary.py` from the exported marts (types) and `dbt/models/schema.yml`",
        "(descriptions, grain). These are the tables Power BI and Tableau read.",
        "",
    ]
    for mart in MARTS:
        model = models.get(mart, {})
        grain = next(
            (
                t["unique_combination"]["columns"]
                for t in model.get("data_tests", [])
                if isinstance(t, dict) and "unique_combination" in t
            ),
            None,
        )
        described = {c["name"]: c.get("description", "") for c in model.get("columns", [])}
        lines += [f"## {mart}", "", model.get("description", ""), ""]
        if grain:
            lines += [f"Grain: one row per {', '.join(f'`{c}`' for c in grain)}.", ""]
        lines += ["| Column | Type | Meaning |", "|---|---|---|"]
        for field in pq.read_schema(ROOT / f"bi/exports/{mart}.parquet"):
            meaning = described.get(field.name) or NOTES.get(field.name, "")
            lines.append(f"| `{field.name}` | {field.type} | {meaning} |")
        lines.append("")
    out = ROOT / "docs/DATA-DICTIONARY.md"
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out.relative_to(ROOT)}: {len(MARTS)} tables")


if __name__ == "__main__":
    main()
